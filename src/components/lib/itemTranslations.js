export function getLocalizedPlace(place, lang = "en") {
  if (!place) return place;
  if (lang === "en") return place;

  const key = place.id || place.name?.toLowerCase().replace(/\s+/g, "-");
  const match = translations.places[key] || Object.values(translations.places).find((p) => p[lang]?.name === place.name);
  const localized = match?.[lang];

  if (!localized) return place;
  return {
    ...place,
    name: localized.name || place.name,
    tag: localized.tag || place.tag,
    state: localized.state || place.state,
    description: localized.description || place.description,
  };
}

export function getLocalizedFood(food, lang = "en") {
  if (!food) return food;
  if (lang === "en") return food;

  const match = translations.foods[food.name];
  const localized = match?.[lang];

  if (!localized) return food;
  return {
    ...food,
    name: localized.name || food.name,
    state: localized.state || food.state,
    description: localized.description || food.description,
  };
}

export function getLocalizedProduct(product, lang = "en") {
  if (!product) return product;
  if (lang === "en") return product;

  const match = translations.products[product.name] || translations.products[product.title];
  const localized = match?.[lang];

  if (!localized) return product;
  return {
    ...product,
    name: localized.name || product.name || product.title,
    origin: localized.origin || product.origin || product.craft_origin,
    description: localized.description || product.description,
  };
}
