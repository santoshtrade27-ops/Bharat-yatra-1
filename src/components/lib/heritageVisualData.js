export function findMatchingVisual(query = "", category = "all") {
  const q = query.toLowerCase().trim();
  const allItems = [...HERITAGE_SITES_LIBRARY, ...LOCAL_CRAFTS_LIBRARY];

  if (!q) {
    return allItems[Math.floor(Math.random() * allItems.length)];
  }

  // Exact or substring match
  const matched = allItems.find(item => 
    item.title.toLowerCase().includes(q) ||
    item.state.toLowerCase().includes(q) ||
    item.tags.some(t => t.toLowerCase().includes(q)) ||
    q.includes(item.title.toLowerCase()) ||
    q.includes(item.state.toLowerCase())
  );

  if (matched) return matched;

  // Category filter fallback
  if (category === "Local Craft") {
    return LOCAL_CRAFTS_LIBRARY[Math.floor(Math.random() * LOCAL_CRAFTS_LIBRARY.length)];
  }
  return HERITAGE_SITES_LIBRARY[Math.floor(Math.random() * HERITAGE_SITES_LIBRARY.length)];
}
